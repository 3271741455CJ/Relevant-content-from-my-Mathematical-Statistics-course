# 加载 readxl 包
library(readxl)

calculate_T_EP_matrix <- function(file_path) {
  # ---------------------------------------------------------
  # 数据读取阶段
  # ---------------------------------------------------------
  # 提取文件扩展名
  ext <- tolower(tools::file_ext(file_path))
  
  if (ext == "csv") {
    df <- read.csv(file_path, header = FALSE, stringsAsFactors = FALSE)  # header = FALSE 表示第一行就是数据，不是列名
  } else if (ext %in% c("xls", "xlsx")) {
    df <- read_excel(file_path, col_names = FALSE)  # col_names = FALSE 表示第一行就是数据
  } else {
    stop("不支持的文件格式，请提供 csv, xls 或 xlsx 文件。")
  }
  
  # 将多行多列的数据框 (data.frame) 展平为一维向量
  raw_data <- as.numeric(unlist(df))
  
  # 剔除 NA 值（即表格中没有数据的空单元格）
  x <- raw_data[!is.na(raw_data)]
  
  
  # ---------------------------------------------------------
  # 步骤 (1): 存储样本量 n 与样本观察值 x_1, x_2, ..., x_n
  # ---------------------------------------------------------
  n <- length(x)
  
  if (n < 2) {
    stop("样本量必须至少为 2 才能进行计算。")
  }
  cat(sprintf("(1) 成功读取数据，样本量 n = %d\n", n))
  
  
  # ---------------------------------------------------------
  # 步骤 (2): 计算并存储样本均值 x_bar 与样本二阶中心矩 m2
  # ---------------------------------------------------------
  x_bar <- mean(x)
  m2 <- mean((x - x_bar)^2) 
  cat(sprintf("(2) 样本均值 = %.6f, 样本二阶中心矩 m2 = %.6f\n", x_bar, m2))
  
  if (m2 == 0) {
    stop("样本二阶中心矩为 0，无法继续计算 (除数为零)。")
  }
  
  
  # ---------------------------------------------------------
  # 步骤 (3): 计算并存储 A
  # ---------------------------------------------------------
  # 向量化计算，极大地提高 R 的运行效率
  A_terms <- exp(-((x - x_bar)^2) / (4 * m2))
  A <- sum(A_terms)
  cat(sprintf("(3) 计算得 A = %.6f\n", A))
  
  # ---------------------------------------------------------
  # 步骤 (4): 计算并存储 B
  # ---------------------------------------------------------
  B <- 0
  # k 从 2 循环到 n，j 从 1 循环到 k-1
  for (k in 2:n) {
    for (j in 1:(k-1)) {
      B <- B + exp(-((x[j] - x[k])^2) / (2 * m2))
    }
  }
  cat(sprintf("(4) 计算得 B = %.6f\n", B))
  
  
  # ---------------------------------------------------------
  # 步骤 (5): 计算并输出 T_EP
  # ---------------------------------------------------------
  T_EP <- 1 + (n / sqrt(3)) + ((2 / n) * B) - (sqrt(2) * A)
  cat(sprintf("(5) 最终计算结果 T_EP = %.6f\n", T_EP))
  
  
  return(T_EP)
}



# 指定数据文件   在下面的""内填入具体的路径（使用绝对路径）以及存储原始数据的文件名
  ## 这里以  D:/Data.xlsx  为例
